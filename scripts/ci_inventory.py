"""Render the validated CI registry for readers; never schedule or run jobs."""
import argparse
import json
from . import ci_suites as suites

DOCUMENT = 'docs/CI_JOB_INVENTORY.md'


def cell(value):
    return str(value).replace('|', '&#124;').replace('\n', '<br>')


def render(root=suites.ROOT):
    registry = suites.check(root)
    rows = registry['suites']
    count = len(suites.expanded_names(registry))
    integration = len(suites.expanded_names(dict(metaJobs=registry['metaJobs'], suites=[r for r in rows if r['integrationResult']=='success'])))
    lines = [
        '# Current CI job inventory', '',
        'Generated by `python3 -m scripts.ci_inventory` after validating the actual',
        '[workflow](../.github/workflows/ci.yml), local actions, release interfaces and',
        '[suite registry](../scripts/ci_suite_registry.json). Do not edit this table by hand.', '',
        f'**{len(rows)} suites + 2 meta jobs = {len(rows)+2} static job IDs; {count} expanded full jobs.**',
        f'Docs mode reports Change scope and Required plus {len(rows)} skipped suite placeholders.',
        'These are configuration counts, not measurements of a particular run.',
        f'Integration executes {integration} instances: only the complete canonical suite is skipped.',
        'Every suite requires `success` in full and `skipped` in docs. Exact rules and',
        'forceFull are defined in [the tiered policy](CI_TIERED_DESIGN.md); unknown paths stay full.',
        'All jobs currently use `ubuntu-latest`; matrix fail-fast is false.', '',
        '| Suite ID | Display name | Build / responsibility domain | Needs | Full jobs | Job ceiling (min) |',
        '| --- | --- | --- | --- | ---: | ---: |',
    ]
    for row in rows:
        names = suites.expanded_names(dict(metaJobs={}, suites=[row]))
        values = [row['id'], row['name'], row['domain'], ', '.join(row['needs']), len(names), row['timeoutMinutes']]
        lines.append('| ' + ' | '.join(cell(v) for v in values) + ' |')
    lines += ['', '## Fixed matrix members', '',
              'Rows and their order are part of the contract; the cloud parser checks them independently.', '']
    for row in rows:
        if row['matrix'] is not None:
            lines += ['### ' + row['id'], '', '```json', json.dumps(row['matrix'], indent=2), '```', '']
    downloads = sum(len(row['inputs']) for row in rows)
    uploads = sum(len(row['evidence']) for row in rows)
    lines += ['## Meta jobs and evidence', '',
              '- `changes` / `Change scope` has no job dependencies and produces the source-bound execution plan.',
              f'- `required` / `Required` always evaluates Change scope and all {len(rows)} suite results.',
              f'- The suites declare {downloads} download and {uploads} upload operations before matrix expansion.',
              '- Change scope retains the execution receipt, complete change records and a diagnostic shadow report.',
              '- Exact artifact IDs, paths, conditions, retention and external step names are in the registry.', '',
              'See [dependency and consumer contracts](CI_DEPENDENCY_CONTRACTS.md),',
              '[operations](CI_CD.md) and [new-suite onboarding](CI_SUITE_ONBOARDING.md).', '']
    return '\n'.join(lines)


def check_document(root=suites.ROOT):
    expected = render(root)
    suites.need((root / DOCUMENT).read_text(encoding='utf-8') == expected,
                'CI inventory documentation stale; regenerate with python3 -m scripts.ci_inventory')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='reject a stale committed inventory')
    args = parser.parse_args()
    try:
        if args.check:
            check_document()
            print(json.dumps(dict(status='PASS', document=DOCUMENT)))
        else:
            print(render(), end='')
    except (ValueError, OSError, KeyError, TypeError, RecursionError) as error:
        parser.exit(1, 'CI inventory failed: ' + str(error) + '\n')


if __name__ == '__main__':
    main()
