def contract():
    source = origin.contract(); need(source == render(), 'V5.2 Runner source-owned workflow drift'); return source


def outputs(values, env):
    need(set(values) <= {'provider', 'serviceAccount', 'artifactName'} and all(type(v) is str and v and
         not any(c.isspace() or ord(c) < 32 for c in v) for v in values.values()), 'V5.2 workflow output fields')
    target = env.get('GITHUB_OUTPUT'); need(type(target) is str and target, 'V5.2 missing Actions output')
    fd = os.open(target, os.O_WRONLY|os.O_APPEND|os.O_NOFOLLOW)
    with os.fdopen(fd, 'a') as stream:
        need(stat.S_ISREG(os.fstat(stream.fileno()).st_mode), 'V5.2 Actions output type')
        for name, value in values.items(): stream.write(name+'='+value+'\n')


def identity_native(source, output):
    from . import cloud_operator as operator
    env = dict(os.environ); operator.environment(env)
    cfg = reads.source_configuration(source); contract()
    bound = credentials.identity(cfg['provider'], cfg['projectNumber'], env, role='runner', source=source, checkout=source)
    observed = credentials.collect_run(bound, lambda path, end:credentials.github(path, end, time.monotonic), time.monotonic()+30, time.monotonic)
    need(reads.source_configuration(source) == cfg, 'V5.2 Runner bootstrap source changed')
    output = Path(output); need(not any(p.is_symlink() for p in (output, *output.parents)), 'V5.2 identity output link')
    output.mkdir(parents=True, exist_ok=False)
    artifacts.save(output/'identity.json', dict(binding=bound, runObservation=observed, credentialExchangeCompleted=False))
    outputs({k:bound[k] for k in ('provider', 'serviceAccount')}, env)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__); parser.add_argument('action', choices=('check', 'identity'))
    parser.add_argument('--source'); parser.add_argument('--output', type=Path); args = parser.parse_args()
    if args.action == 'check': contract(); print('v52RunnerWorkflow=PASS')
    else:
        if not args.source or not args.output: parser.error('identity requires source/output')
        identity_native(args.source, args.output); print('v52RunnerIdentity=BOUND_NOT_AUTHENTICATED')
