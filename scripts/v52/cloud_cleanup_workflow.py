def contract(root=preflight.ROOT):
    value=artifacts.inputs.regular(Path(root)/PATH,65536).decode()
    need(value==render(),'V5.2 manual cleanup workflow changed')
    return value


def identity_native(source, output):
    """Select fixed WIF outputs before google/auth, without exchanging a token."""
    output=Path(output);need(not any(p.is_symlink() for p in (output,*output.parents)),'V5.2 identity output symlink')
    output.mkdir(parents=True,exist_ok=False)
    cfg=preflight.source_configuration(source);contract();env=dict(os.environ)
    bound=credentials.identity(cfg['provider'],cfg['projectNumber'],env,role='manual',source=source,checkout=source)
    observed=credentials.collect_run(bound,lambda path,end:credentials.github(path,end,time.monotonic),time.monotonic()+30,time.monotonic)
    need(encoded(preflight.source_configuration(source))==encoded(cfg),'V5.2 bootstrap source changed')
    receipt=dict(schema='gse-v52-cleanup-bootstrap-v1',binding=bound,runObservation=observed,credentialExchangeCompleted=False)
    artifacts.save(output/'identity.json',receipt)
    target=env.get('GITHUB_OUTPUT');need(type(target) is str and target,'V5.2 missing Actions output')
    # Only the already validated service account/provider are published. No
    # newline or caller-provided value can add another output/credential.
    fd=os.open(target,os.O_WRONLY|os.O_APPEND|os.O_NOFOLLOW)
    with os.fdopen(fd,'a') as stream:
        need(stat.S_ISREG(os.fstat(stream.fileno()).st_mode),'V5.2 Actions output type')
        stream.write('provider='+bound['provider']+'\nserviceAccount='+bound['serviceAccount']+'\n')
    return receipt


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('action',choices=('identity','check'))
    parser.add_argument('--source');parser.add_argument('--output',type=Path);args=parser.parse_args()
    if args.action=='check':contract();print('v52CleanupWorkflow=PASS')
    else:
        if not args.source or not args.output:parser.error('identity requires source/output')
        identity_native(args.source,args.output);print('v52CleanupIdentity=BOUND_NOT_AUTHENTICATED')
