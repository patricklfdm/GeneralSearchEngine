"""Manual, unprivileged V5.2 producer derived from the existing tested build."""
from pathlib import Path
from scripts import ci_suites as suites
from .evidence import need

ROOT = Path(__file__).resolve().parents[2]
WORKFLOW = '.github/workflows/v52-cloud-build.yml'
JOB = 'V5.2 cloud build'
JOB_ID = 'cloud-build'


def render(root=ROOT):
    # Keep commands, toolchain, pinned actions and original bundle format aligned
    # with CI. Changing that producer requires regenerating this reviewed file.
    body = suites.job_blocks(suites.read(root, suites.WORKFLOW))['v51-verification-build']
    replacements = {
        '    name: V5.1 verification build': '    name: '+JOB,
        '    needs: changes\n': '',
        "    if: ${{ needs.changes.outputs.run_full_ci == 'true' }}": "    if: ${{ github.ref == 'refs/heads/master' }}",
        '    timeout-minutes: 30': '    timeout-minutes: 60',
        '          retention-days: 14': '          retention-days: 90',
    }
    for old, new in replacements.items():
        need(old in body, 'V5.2 manual build source changed'); body = body.replace(old, new)
    lines = body.splitlines()
    checkout = next(i for i, line in enumerate(lines) if 'uses: actions/checkout@' in line)
    lines[checkout+1:checkout+1] = ['        with:', '          ref: ${{ github.sha }}',
                                  '          persist-credentials: false']
    return '''# Generated by python3 -m scripts.v52.cloud_build_workflow; no cloud authority.
name: V5.2 Cloud Build

on:
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: v52-cloud-build
  cancel-in-progress: false

env:
  MAVEN_ARGS: --batch-mode --no-transfer-progress -Dstyle.color=never

jobs:
  cloud-build:
'''+ '\n'.join(lines)+'\n'


def contract(root=ROOT):
    text = suites.read(root, WORKFLOW)
    need(text == render(root), 'V5.2 manual build workflow changed')
    fields = suites.fields(suites.job_blocks(text)[JOB_ID], 4)
    steps = suites.steps(fields['steps'])
    need(all('if' not in row or suites.scalar(row['if']) == suites.ALWAYS for row in steps.values()),
         'V5.2 manual build conditional step')
    return {JOB: dict(id=JOB_ID, steps=list(steps))}


if __name__ == '__main__':
    (ROOT/WORKFLOW).write_text(render(), encoding='utf-8')
